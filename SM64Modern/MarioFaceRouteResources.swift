enum SM64MarioFaceRouteResourceFingerprint {
    static let offset: UInt64 = 1_469_598_103_934_665_603
    static let prime: UInt64 = 1_099_511_628_211

    private static func hash(_ initial: UInt64, _ value: UInt64) -> UInt64 {
        var result = initial
        for byte in 0..<8 {
            result ^= (value >> UInt64(byte * 8)) & 0xFF
            result &*= prime
        }
        return result
    }

    private static func hash(_ initial: UInt64, _ value: UInt32) -> UInt64 {
        hash(initial, UInt64(value))
    }

    private static func hash(_ initial: UInt64, _ value: Int32) -> UInt64 {
        hash(initial, UInt64(bitPattern: Int64(value)))
    }

    private static func hash(_ initial: UInt64, _ values: [UInt32]) -> UInt64 {
        values.reduce(initial) { hash($0, $1) }
    }

    private static func hash(_ initial: UInt64, _ values: [Int32]) -> UInt64 {
        values.reduce(initial) { hash($0, $1) }
    }

    private static func hash(_ initial: UInt64, _ string: String) -> UInt64 {
        var result = hash(initial, UInt64(string.utf8.count))
        for byte in string.utf8 {
            result = hash(result, UInt64(byte))
        }
        return result
    }

    private static func hash(_ initial: UInt64, _ camera: SM64MarioFaceCameraOrientationRecord) -> UInt64 {
        var result = hash(initial, camera.routeID.rawValue)
        result = hash(result, camera.viewSymbol)
        result = hash(result, [
            camera.viewportWidth, camera.viewportHeight, camera.rendererScale100000,
            camera.mainScale100000, camera.cursorX, camera.cursorY, camera.lightCount,
        ])
        result = hash(result, [
            camera.rendererPitchMinDegrees100, camera.rendererPitchMaxDegrees100,
            camera.mainPitchMinDegrees100, camera.mainPitchMaxDegrees100,
        ])
        result = hash(result, camera.lightDirection)
        return hash(result, camera.lightScaleRGB1000)
    }

    static func catalog(
        textures: [SM64MarioFaceTextureResource] = SM64MarioFaceRouteResourceCatalog.textures,
        routes: [SM64MarioFaceRouteRecord] = SM64MarioFaceRouteResourceCatalog.routes
    ) -> UInt64 {
        var result = hash(offset, UInt64(1))
        result = hash(result, UInt64(textures.count))
        for texture in textures {
            result = hash(result, [
                texture.textureID, texture.format.rawValue, texture.bitsPerTexel,
                texture.width, texture.height, texture.frameIndex,
                texture.family.rawValue, texture.policyFlags,
            ])
            result = hash(result, texture.symbol)
            result = hash(result, texture.includePath)
        }
        result = hash(result, UInt64(routes.count))
        for route in routes {
            result = hash(result, [
                route.routeID.rawValue, route.displayListID,
                route.updateDomain.rawValue, route.policyFlags,
                UInt32(route.textureIDs.count),
            ])
            result = hash(result, route.viewSymbol)
            result = hash(result, route.objectSymbol)
            result = hash(result, route.textureIDs)
            result = hash(result, SM64MarioFaceRouteResourceCatalog.camera(for: route))
        }
        return result
    }
}

struct SM64MarioFaceRouteRenderPacket: Equatable, Sendable {
    let route: SM64MarioFaceRouteRecord
    let camera: SM64MarioFaceCameraOrientationRecord
    let textures: [SM64MarioFaceTextureResource]
    let face: SM64MarioFaceRenderFramePacket
    let resourceFingerprint: UInt64
    let fingerprint: UInt64
}

enum SM64MarioFaceRouteRenderPacketBuilder {
    static func make(
        routeID: SM64MarioFaceGoddardRouteID,
        face: SM64MarioFaceRenderFramePacket
    ) -> SM64MarioFaceRouteRenderPacket? {
        guard let route = SM64MarioFaceRouteResourceCatalog.route(routeID) else { return nil }
        let camera = SM64MarioFaceRouteResourceCatalog.camera(for: route)
        let textures = route.textureIDs.compactMap(SM64MarioFaceRouteResourceCatalog.texture)
        guard textures.count == route.textureIDs.count else { return nil }
        let resourceFingerprint = SM64MarioFaceRouteResourceFingerprint.catalog()
        var fingerprint = SM64MarioFaceRouteResourceFingerprint.offset
        fingerprint = hash(fingerprint, resourceFingerprint)
        fingerprint = hash(fingerprint, route.routeID.rawValue)
        fingerprint = hash(fingerprint, camera.viewportWidth)
        fingerprint = hash(fingerprint, camera.viewportHeight)
        fingerprint = hash(fingerprint, SM64MarioFaceRenderPacketFingerprint.packet(face))
        fingerprint = hash(fingerprint, UInt64(textures.count))
        for texture in textures { fingerprint = hash(fingerprint, texture.textureID) }
        return SM64MarioFaceRouteRenderPacket(
            route: route, camera: camera, textures: textures, face: face,
            resourceFingerprint: resourceFingerprint, fingerprint: fingerprint
        )
    }

    private static func hash(_ initial: UInt64, _ value: UInt64) -> UInt64 {
        var result = initial
        for byte in 0..<8 {
            result ^= (value >> UInt64(byte * 8)) & 0xFF
            result &*= SM64MarioFaceRouteResourceFingerprint.prime
        }
        return result
    }

    private static func hash(_ initial: UInt64, _ value: UInt32) -> UInt64 {
        hash(initial, UInt64(value))
    }
}

/// Schema-4 render-domain records for the route/resource packet.  The first
/// records are entirely source metadata and can be compared before a Metal
/// encoder is involved; the final record carries the already-qualified M30l
/// face-packet fingerprint.
enum SM64MarioFaceRouteRenderOracle {
    static let domain: UInt32 = SM64RenderOracleTraceAdapter.domain
    static let recordKind: UInt32 = SM64RenderOracleTraceAdapter.recordKind
    /// C's `sm64_modern_parity_record_mario_face_route` uses the render
    /// inventory event ID below. Its values deliberately stay at the copied
    /// route/camera boundary; texture/resource fingerprints remain separate
    /// records so this hook never receives a pointer or a Metal handle.
    static let liveCEventID: UInt64 = 5
    static let routeRecordBase: UInt64 = 0x4D46_5200
    static let cameraRecordBase: UInt64 = 0x4D46_5300
    static let textureRecordBase: UInt64 = 0x4D46_5400
    static let faceRecordBase: UInt64 = 0x4D46_5500

    static func metadataRecords(
        route: SM64MarioFaceRouteRecord,
        camera: SM64MarioFaceCameraOrientationRecord,
        textures: [SM64MarioFaceTextureResource],
        simulationTick: UInt64,
        sequenceStart: UInt32
    ) throws -> [SM64OracleTraceRecord] {
        var sequence = sequenceStart
        var records = [
            try SM64OracleTraceRecord(
                simulationTick: simulationTick, domain: domain,
                recordKind: recordKind, subjectID: UInt64(route.routeID.rawValue),
                recordID: routeRecordBase | UInt64(route.routeID.rawValue),
                sequence: sequence,
                values: [
                    UInt64(route.routeID.rawValue), UInt64(route.displayListID),
                    UInt64(route.updateDomain.rawValue), UInt64(route.policyFlags),
                    UInt64(textures.count), UInt64(camera.viewportWidth),
                    UInt64(camera.viewportHeight),
                    SM64MarioFaceRouteResourceFingerprint.catalog(),
                ]
            )
        ]
        sequence &+= 1
        records.append(try SM64OracleTraceRecord(
            simulationTick: simulationTick, domain: domain,
            recordKind: recordKind, subjectID: UInt64(route.routeID.rawValue),
            recordID: cameraRecordBase | UInt64(route.routeID.rawValue),
            sequence: sequence,
            values: [
                UInt64(camera.viewportWidth), UInt64(camera.viewportHeight),
                UInt64(camera.rendererScale100000),
                UInt64(bitPattern: Int64(camera.rendererPitchMinDegrees100)),
                UInt64(bitPattern: Int64(camera.rendererPitchMaxDegrees100)),
                UInt64(camera.mainScale100000),
                UInt64(bitPattern: Int64(camera.mainPitchMinDegrees100)),
                UInt64(bitPattern: Int64(camera.mainPitchMaxDegrees100)),
            ]
        ))
        sequence &+= 1
        for texture in textures {
            records.append(try SM64OracleTraceRecord(
                simulationTick: simulationTick, domain: domain,
                recordKind: recordKind, subjectID: UInt64(route.routeID.rawValue),
                recordID: textureRecordBase | UInt64(texture.textureID),
                sequence: sequence,
                values: [
                    UInt64(texture.textureID), UInt64(texture.format.rawValue),
                    UInt64(texture.bitsPerTexel), UInt64(texture.width),
                    UInt64(texture.height), UInt64(texture.frameIndex),
                    UInt64(texture.family.rawValue), UInt64(texture.policyFlags),
                ]
            ))
            sequence &+= 1
        }
        return records
    }

    static func records(
        packet: SM64MarioFaceRouteRenderPacket,
        simulationTick: UInt64,
        sequenceStart: UInt32 = 0
    ) throws -> [SM64OracleTraceRecord] {
        var records = try metadataRecords(
            route: packet.route, camera: packet.camera, textures: packet.textures,
            simulationTick: simulationTick, sequenceStart: sequenceStart
        )
        records.append(try SM64OracleTraceRecord(
            simulationTick: simulationTick, domain: domain,
            recordKind: recordKind, subjectID: UInt64(packet.route.routeID.rawValue),
            recordID: faceRecordBase | UInt64(packet.route.routeID.rawValue),
            sequence: records.last.map { $0.sequence &+ 1 } ?? sequenceStart,
            values: [
                SM64MarioFaceRenderPacketFingerprint.packet(packet.face),
                packet.fingerprint, packet.resourceFingerprint,
                UInt64(packet.face.animationBank), UInt64(packet.face.animationFrameQ16),
                UInt64(packet.face.residentChannelCount),
                UInt64(packet.face.unavailableChannelCount),
                packet.face.channelMask,
            ]
        ))
        return records
    }

    static func liveCRecord(
        route: SM64MarioFaceRouteRecord,
        simulationTick: UInt64,
        sequence: UInt32
    ) throws -> SM64OracleTraceRecord {
        try SM64OracleTraceRecord(
            simulationTick: simulationTick,
            domain: domain,
            recordKind: recordKind,
            subjectID: 0,
            recordID: liveCEventID,
            sequence: sequence,
            values: [
                UInt64(route.routeID.rawValue), UInt64(route.displayListID),
                UInt64(route.updateDomain.rawValue), UInt64(route.policyFlags),
                320, 240, 2,
            ]
        )
    }

    static func fingerprint(_ records: [SM64OracleTraceRecord]) -> UInt64 {
        var result = SM64OracleTraceHash.offset
        result = update(result, UInt64(records.count))
        for record in records { result = update(result, record.canonicalHash) }
        return result
    }

    private static func update(_ initial: UInt64, _ value: UInt64) -> UInt64 {
        var result = initial
        for byte in 0..<8 {
            result ^= (value >> UInt64(byte * 8)) & 0xFF
            result &*= SM64OracleTraceHash.prime
        }
        return result
    }
}
