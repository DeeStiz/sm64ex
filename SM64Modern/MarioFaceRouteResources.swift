import Foundation

/// The six display-list routes accepted by `gdm_gettestdl` in
/// `src/goddard/renderer.c`.  These are source route IDs, not Metal texture
/// IDs and not pointers into the legacy object graph.
enum SM64MarioFaceGoddardRouteID: UInt32, CaseIterable, Sendable {
    case yoshiScene = 0
    case yoshiShell = 1
    case marioNormal = 2
    case marioGameOver = 3
    case carScene = 4
    case testnet2 = 5
}

enum SM64MarioFaceGoddardUpdateDomain: UInt32, Sendable {
    case none = 0
    case yoshiScene = 1
    case marioScene = 2
    case carScene = 3
}

enum SM64MarioFaceTextureFormat: UInt32, Sendable {
    case rgba16 = 1
    case ia8 = 2
}

enum SM64MarioFaceTextureFamily: UInt32, Sendable {
    case hand = 1
    case redStar = 2
    case whiteStar = 3
    case faceShine = 4
}

struct SM64MarioFaceTextureResource: Equatable, Sendable {
    let textureID: UInt32
    let symbol: String
    let includePath: String
    let format: SM64MarioFaceTextureFormat
    let bitsPerTexel: UInt32
    let width: UInt32
    let height: UInt32
    let frameIndex: UInt32
    let family: SM64MarioFaceTextureFamily
    /// Source sampler/material facts. Bit 0 = texture generation, bit 1 =
    /// bilinear filtering, bit 2 = wrap in both axes.
    let policyFlags: UInt32
}

struct SM64MarioFaceRouteRecord: Equatable, Sendable {
    let routeID: SM64MarioFaceGoddardRouteID
    let displayListID: UInt32
    let viewSymbol: String
    let objectSymbol: String
    let updateDomain: SM64MarioFaceGoddardUpdateDomain
    /// Bit 0 = route is the Mario-face path, bit 1 = hand view is updated,
    /// bit 2 = route allocates/updates a scene view.
    let policyFlags: UInt32
    let textureIDs: [UInt32]
}

struct SM64MarioFaceCameraOrientationRecord: Equatable, Sendable {
    let routeID: SM64MarioFaceGoddardRouteID
    let viewSymbol: String
    let viewportWidth: UInt32
    let viewportHeight: UInt32
    let rendererScale100000: UInt32
    let rendererPitchMinDegrees100: Int32
    let rendererPitchMaxDegrees100: Int32
    let mainScale100000: UInt32
    let mainPitchMinDegrees100: Int32
    let mainPitchMaxDegrees100: Int32
    let cursorX: UInt32
    let cursorY: UInt32
    let lightCount: UInt32
    let lightDirection: [Int32]
    let lightScaleRGB1000: [UInt32]
}

